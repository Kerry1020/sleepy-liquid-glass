#!/usr/bin/env python3
"""Rebuild registered input rasters in an empty external directory, never captures.

The original generators and their freeze files are copied unchanged. No --freeze,
build, device, historical APK-copying generator or optical analyzer is invoked.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
LIBRARY = HERE.parents[2]
ARCHIVE = HERE / 'archive'
PACKETS = {'noise': 'glass-noise-20261114',
           'shapes': 'glass-isolated-shapes-20261114'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def dependencies(python):
    script = ('import json,platform,numpy,PIL; from PIL import features; '
              'print(json.dumps({"python":platform.python_version(),'
              '"numpy":numpy.__version__,"pillow":PIL.__version__,'
              '"littlecms2":features.version("littlecms2")}))')
    return json.loads(subprocess.check_output([python, '-c', script], text=True))


def frozen_rebuild(kind, destination, python, actual_dependencies):
    original = ARCHIVE / PACKETS[kind]
    freeze = json.loads((original / 'freeze.json').read_text())
    if actual_dependencies != freeze['dependencies']:
        raise RuntimeError('Dependency mismatch; do not re-freeze or relabel regenerated bytes: '
                           + json.dumps({'expected': freeze['dependencies'],
                                         'actual': actual_dependencies}))
    for name, expected in freeze['file_sha256'].items():
        if sha((original / name).read_bytes()) != expected:
            raise RuntimeError('Frozen source identity mismatch: ' + name)
    output = destination / PACKETS[kind]
    output.mkdir()
    for name in ['generate.py', 'README.md', 'protocol.json', 'freeze.json', 'sRGB.icc']:
        shutil.copyfile(original / name, output / name)
    receipts = []
    for action in ['--generate', '--verify']:
        result = subprocess.run([python, str(output / 'generate.py'), action],
                                text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        receipt = {'action': action, 'returncode': result.returncode,
                   'stdout': result.stdout, 'stderr': result.stderr}
        receipts.append(receipt)
        (output / 'rebuild-process-receipts.json').write_text(json.dumps(receipts, indent=2) + '\n')
        if result.returncode:
            raise RuntimeError('Original generator failed; evidence retained at ' + str(output))
    comparisons = []
    for split in ['calibration', 'test']:
        expected = json.loads((original / split / 'manifest.json').read_text())
        generated = json.loads((output / split / 'manifest.json').read_text())
        if generated != expected:
            raise RuntimeError('Reconstructed manifest differs from published identity: ' + split)
        comparisons.append({'split': split, 'inputs': len(expected['inputs']),
                            'manifest_sha256': sha((output / split / 'manifest.json').read_bytes()),
                            'matches_registered_manifest': True})
    return {'kind': kind, 'packet': PACKETS[kind], 'comparisons': comparisons,
            'original_generate_and_verify_passed': True}


def flat_rebuild(destination, python):
    # The historical generator also copies APKs from a machine-specific path.
    # This source-only helper deliberately does not import or run that program.
    source = ARCHIVE / 'glass-dock-model-20261114/material-sweep'
    output = destination / 'flat-material-inputs'
    output.mkdir()
    manifest = json.loads((source / 'manifest.json').read_text())
    profile = ARCHIVE / 'glass-isolated-shapes-20261114/sRGB.icc'
    if sha(profile.read_bytes()) != manifest['icc_profile_sha256']:
        raise RuntimeError('Flat material ICC identity mismatch')
    script = r'''
import hashlib,json,sys
from pathlib import Path
from PIL import Image
source,profile,output=map(Path,sys.argv[1:])
manifest=json.loads(source.read_text())
icc=profile.read_bytes()
checks=[]
for entry in manifest['inputs']:
    image=Image.new('RGB',tuple(manifest['dimensions_px']),tuple(entry['rgb']))
    path=output/entry['file']
    image.save(path,icc_profile=icc)
    pixels=hashlib.sha256(image.tobytes()).hexdigest()
    encoded=hashlib.sha256(path.read_bytes()).hexdigest()
    checks.append({'id':entry['id'],'png_matches':encoded==entry['sha256'],
                   'pixels_match':pixels==entry['pixel_sha256'],
                   'png_sha256':encoded,'pixel_sha256':pixels})
(output/'source-only-rebuild-checks.json').write_text(json.dumps(checks,indent=2)+'\n')
assert all(c['png_matches'] and c['pixels_match'] for c in checks), 'Input bytes differ; keep failure evidence'
print(json.dumps({'inputs':len(checks),'all_registered_png_and_pixel_hashes_match':True}))
'''
    result = subprocess.run([python, '-c', script, str(source / 'manifest.json'),
                             str(profile), str(output)], text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    receipt = {'kind': 'flat', 'original_historical_generator_executed': False,
               'returncode': result.returncode, 'stdout': result.stdout, 'stderr': result.stderr}
    (output / 'rebuild-process-receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    if result.returncode:
        raise RuntimeError('Flat input reconstruction failed; evidence retained at ' + str(output))
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--destination', required=True, type=Path,
                        help='New or empty external directory; original archive is never modified')
    parser.add_argument('--kind', choices=['all', 'noise', 'shapes', 'flat'], default='all')
    parser.add_argument('--python', default=sys.executable,
                        help='Interpreter matching the archived dependency fingerprint')
    args = parser.parse_args()
    raw_destination = args.destination.expanduser()
    if raw_destination.is_symlink():
        raise RuntimeError('Destination must not be a symlink')
    destination = raw_destination.resolve()
    if LIBRARY == destination or LIBRARY in destination.parents or destination in LIBRARY.parents:
        raise RuntimeError('Use an external scratch directory, outside this repository')
    if destination.exists() and any(destination.iterdir()):
        raise RuntimeError('Destination is not empty; refusing to overwrite')
    # Check before creating the output tree, including flat-only reconstructions.
    actual_dependencies = dependencies(args.python)
    expected_dependencies = json.loads((ARCHIVE / PACKETS['noise'] / 'freeze.json').read_text())['dependencies']
    if actual_dependencies != expected_dependencies:
        raise RuntimeError('Frozen dependency fingerprint required: ' +
                           json.dumps({'expected': expected_dependencies, 'actual': actual_dependencies}))
    destination.mkdir(parents=True, exist_ok=True)
    receipts = []
    for kind in ['noise', 'shapes', 'flat'] if args.kind == 'all' else [args.kind]:
        receipts.append(flat_rebuild(destination, args.python) if kind == 'flat' else
                        frozen_rebuild(kind, destination, args.python, actual_dependencies))
    report = {'scope': 'generated source inputs only; no output/capture/optical validation',
              'dependencies': actual_dependencies, 'receipts': receipts}
    (destination / 'REBUILD-RECEIPT.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
